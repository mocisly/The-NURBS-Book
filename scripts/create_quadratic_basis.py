"""Create Fig2.6 from exact Cox-de Boor polynomials; verify emitted pieces."""
from pathlib import Path
from fractions import Fraction as F
import json
from bspline_math import piece,evaluate,basis,expression,derivative

root=Path(__file__).resolve().parents[1]
target=root/'image_tex/ch02/fig_2_06.tex'
assert not target.exists(), 'Refuse to overwrite an existing drawing'
knots=(0,0,0,1,2,3,4,4,5,5,5)
lines=['% Fig2.6: exact Cox-de Boor pieces, Ex2.2; generated by create_quadratic_basis.py.',
       '% Polynomial coefficients use Fraction arithmetic. No traced coordinates.',
       r'\begin{tikzpicture}',
       r'\begin{axis}[width=16cm,height=6.2cm,axis lines=left,',
       r'xmin=-.15,xmax=5.65,ymin=0,ymax=1.4,xtick={0,1,2,3,4,5},ytick={1},',
       r'xlabel={$u$},axis line style={-{Stealth}},tick align=outside,clip=false]']
count=0
for i in range(8):
    for span in range(len(knots)-1):
        a,b=knots[span:span+2]
        if a==b: continue
        c=piece(knots,i,2,span)
        if not any(c): continue
        lines.append(f'% N_{{{i},2}} on [{a},{b})')
        shorten=',shorten >=1.5pt' if i==7 and b==5 else ''
        lines.append(r'\addplot[book line,no marks,samples=41,domain='+f'{a}:{b}'+shorten+'] {'+expression(c)+'};')
        for k in range(41):
            x=F(a)+F(k,41)*(b-a)
            assert evaluate(c,x)==basis(knots,i,2,x)
            count+=1
for span in range(len(knots)-1):
    a,b=knots[span:span+2]
    if a==b: continue
    for k in range(41):
        x=F(a)+F(k,41)*(b-a)
        values=[evaluate(piece(knots,i,2,span),x) for i in range(8)]
        assert min(values)>=0 and sum(values)==1
# Interior simple knots are C1; double knot 4 is C0 with derivative jump.
for knot in (1,2,3,4):
    left=next(s for s in range(10) if knots[s]<knots[s+1]==knot)
    right=next(s for s in range(10) if knots[s]==knot<knots[s+1])
    for i in range(8):
        a,b=piece(knots,i,2,left),piece(knots,i,2,right)
        assert evaluate(a,F(knot))==evaluate(b,F(knot))
        if knot!=4: assert evaluate(derivative(a),F(knot))==evaluate(derivative(b),F(knot))
assert evaluate(derivative(piece(knots,5,2,5)),F(4))==2
assert evaluate(derivative(piece(knots,5,2,7)),F(4))==-2
for x,y,i in [(.12,1,0),(2/3,2/3,1),(1.5,.75,2),(2.5,.75,3),(10/3,2/3,4),(4,1,5),(4.5,.5,6),(5,1,7)]:
    lines.append(r'\node[above=5pt] at (axis cs:'+f'{x:.6f},{y:.6f}'+') {$N_{'+f'{i},2'+'}$};')
lines.extend(['% Right endpoint follows P2.8/FindSpan: N7,2(5)=1.',
              r'\fill (axis cs:5,1) circle[radius=1.5pt];',
              r'\pgfplotsinvokeforeach{-.035,.035,4.035,4.965,5.035}{',
              r'\draw[book grid] (axis cs:#1,-.02)--(axis cs:#1,.02);}',
              r'\end{axis}',r'\end{tikzpicture}'])
target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
(root/'image_tex/build/quadratic-basis-check.json').write_text(json.dumps({
    'exact_piece_vs_independent_recurrence_checks':count,
    'partition_and_nonnegativity_grid_points':205,
    'simple_knots_C1':True,'double_knot_4_C0':True,
    'N52_left_and_right_derivative_at_4':[2,-2]},indent=2)+'\n')
print(f'Created {target}; {count} exact recurrence comparisons passed.')
