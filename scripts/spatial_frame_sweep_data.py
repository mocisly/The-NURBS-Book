def mul(a,b):
    c=[F(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):c[i+j]+=x*y
    return add(tuple(c),(F(0),))
def dotpoly(a,b):
    c=(F(0),)
    for x,y in zip(a,b):c=add(c,mul(x,y))
    return c
